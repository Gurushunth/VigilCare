// Generates public/sw-manifest.js after `next build`: every URL the service
// worker must precache so a full reload works with the network off.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(new URL(".", import.meta.url).pathname, "..");
const nextDir = join(root, ".next");
const publicDir = join(root, "public");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const toUrl = (base, p) => base + relative(base === "/" ? publicDir : join(nextDir, "static"), p).split(sep).join("/");

if (!existsSync(join(nextDir, "BUILD_ID"))) {
  console.error("gen-sw-manifest: run `next build` first");
  process.exit(1);
}
const buildId = readFileSync(join(nextDir, "BUILD_ID"), "utf8").trim();

const staticUrls = walk(join(nextDir, "static"))
  .filter((p) => !p.endsWith(".map"))
  .map((p) => toUrl("/_next/static/", p));

const publicUrls = walk(publicDir)
  .filter((p) => !/(^|\/)(sw\.js|sw-manifest\.js|\.DS_Store)$/.test(p))
  .map((p) => toUrl("/", p));

const routes = ["/", "/demo", "/favicon.ico"];
const urls = [...new Set([...routes, ...staticUrls, ...publicUrls])];

writeFileSync(
  join(publicDir, "sw-manifest.js"),
  `// Generated by scripts/gen-sw-manifest.mjs. Do not edit.\nself.__PS_BUILD_ID = ${JSON.stringify(buildId)};\nself.__PS_PRECACHE = ${JSON.stringify(urls, null, 1)};\n`,
);
console.log(`gen-sw-manifest: ${urls.length} URLs for build ${buildId}`);
